    private fun remapVaultSubject(
        source: VaultSubjectNode,
        newSubjectId: String,
        newBatchId: String,
    ): VaultSubjectNode = source.copy(
        id = newSubjectId,
        batchId = newBatchId,
        chapters = source.chapters.map { chapter ->
            val newChapterId = "${newBatchId}_${chapter.id}"
            chapter.copy(
                id = newChapterId,
                batchId = newBatchId,
                subjectId = newSubjectId,
                lectures = chapter.lectures.map { lecture ->
                    lecture.copy(
                        id = "${newBatchId}_${lecture.id}",
                        batchId = newBatchId,
                        subjectId = newSubjectId,
                        chapterId = newChapterId,
                    )
                },
            )
        },
    )
